import AppKit
import Carbon.HIToolbox

/// Puts text at the cursor of whatever app has focus.
enum TextInserter {
    static func insert(_ text: String, config: Config.Insertion) {
        if config.method == "type" {
            typeText(text)
        } else {
            paste(text, restoreClipboard: config.restoreClipboard)
        }
    }

    // MARK: Pasteboard + Cmd-V

    /// The user's clipboard waiting to be put back. Back-to-back pastes reuse it instead of
    /// snapshotting the previous transcript.
    private static var pendingRestore: (items: [NSPasteboardItem], work: DispatchWorkItem)?

    private static func paste(_ text: String, restoreClipboard: Bool) {
        let pb = NSPasteboard.general
        var saved: [NSPasteboardItem]?
        if let pending = pendingRestore {
            pending.work.cancel()
            pendingRestore = nil
            if restoreClipboard { saved = pending.items }
        } else if restoreClipboard {
            saved = snapshot(pb)
        }

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if restoreClipboard {
            // Ask clipboard managers (nspasteboard.org convention) not to record this temporary entry.
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        pb.clearContents()
        pb.writeObjects([item])
        let ourChange = pb.changeCount
        postKey(vKeyCode(), flags: .maskCommand)

        guard let saved else { return }
        // Give the target app time to read the pasteboard before putting the old contents back.
        let work = DispatchWorkItem {
            pendingRestore = nil
            guard pb.changeCount == ourChange else { return } // the user copied something meanwhile
            pb.clearContents()
            if !saved.isEmpty { pb.writeObjects(saved) }
        }
        pendingRestore = (saved, work)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    /// The key that produces "v" with Cmd held in the current layout (Dvorak, AZERTY, ...). QWERTY's is 9.
    private static func vKeyCode() -> CGKeyCode {
        guard let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return CGKeyCode(kVK_ANSI_V) }
        let layoutData = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return layoutData.withUnsafeBytes { raw -> CGKeyCode in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else {
                return CGKeyCode(kVK_ANSI_V)
            }
            let cmd = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<128 {
                var dead: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var length = 0
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), cmd,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &dead, chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(("v" as Unicode.Scalar).value) {
                    return CGKeyCode(code)
                }
            }
            return CGKeyCode(kVK_ANSI_V)
        }
    }

    private static func postKey(_ code: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            guard let e = CGEvent(keyboardEventSource: source, virtualKey: code, keyDown: down) else { continue }
            e.flags = flags
            e.setIntegerValueField(.eventSourceUserData, value: murmurEventTag)
            e.post(tap: .cgSessionEventTap)
        }
    }

    // MARK: Synthesized typing

    /// Types text as Unicode keystrokes, for apps that block or mangle paste.
    private static func typeText(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let units = Array(text.utf16)
        var i = 0
        while i < units.count {
            var end = min(i + 16, units.count)
            // Don't split a surrogate pair across events.
            if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
            var chunk = Array(units[i..<end])
            for down in [true, false] {
                guard let e = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down) else { continue }
                e.flags = []
                e.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: &chunk)
                e.setIntegerValueField(.eventSourceUserData, value: murmurEventTag)
                e.post(tap: .cgSessionEventTap)
            }
            usleep(2_000)
            i = end
        }
    }
}
